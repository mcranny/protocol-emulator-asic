"""Generate docs/isa.md from the opcode table.

The instruction reference is generated so it cannot drift from the assembler.
``tests/v3/test_isa_reference.py`` fails if the committed page is stale.

Run from the repository root::

    python tools/v3_isa_reference.py
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "host"))

from protocol_emulator.v3 import opcodes  # noqa: E402

PAGE = ROOT / "docs" / "isa.md"


def _fields(op: opcodes.Op) -> str:
    if not op.fields:
        return "none"
    return ", ".join(f"{field.name}[{field.width}] at bit {field.shift}" for field in op.fields)


def render() -> str:
    """Return the full text of the instruction reference."""
    lines = [
        "# Instruction set",
        "",
        "Generated by `tools/v3_isa_reference.py`. Do not edit.",
        "",
        "A word is 32 bits. The opcode is bits 31:26 and the operand is bits 25:0.",
        "Operand fields are packed from bit 0 in the order listed. A word with a",
        "bit set outside those fields is illegal, and so is an opcode that is not",
        "in this table. `single` retires in one cycle, a taken `branch` costs two,",
        "and `stall` holds until its condition is met.",
        "",
        "| Instruction | Opcode | Class | Operand fields |",
        "|---|---|---|---|",
    ]
    for op in opcodes.OPS.values():
        lines.append(
            f"| `{op.name}` | `0x{op.code:02X}` | {op.timing} | {_fields(op)} |"
        )
    lines += [
        "",
        "## Branch conditions",
        "",
        "`BRC` selects one of these with its `condition` field. Any other value",
        "makes the word illegal.",
        "",
        "| Condition | Value |",
        "|---|---|",
    ]
    for name, value in opcodes.CONDITIONS.items():
        lines.append(f"| `{name}` | {value} |")
    lines += [
        "",
        "## Edge polarities",
        "",
        "`WAITEDGE` selects one of these with its `polarity` field. Any other",
        "value makes the word illegal.",
        "",
        "| Polarity | Value |",
        "|---|---|",
    ]
    for name, value in opcodes.POLARITIES.items():
        lines.append(f"| `{name}` | {value} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    PAGE.write_text(render(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
